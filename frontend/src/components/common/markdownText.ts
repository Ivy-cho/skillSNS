// 마크다운을 한 줄 미리보기용 평문으로 바꾼다.
// 목록·채팅 미리보기처럼 **서식을 그릴 수 없는 자리**에서 쓴다. 서식을 살려 보여줄 때는
// Markdown.tsx를 쓸 것 — 여기서는 기호를 지우고 한 줄로 눌러 담는 게 목적이다.
// (에이전트 답변은 제목·표·인용이 섞인 마크다운이라, 그대로 두면 "# 제목 --- **[값]**"처럼 보인다.)
export function toPlainText(markdown: string): string {
  return (
    markdown
      // 코드 펜스는 통째로 버린다 (한 줄 미리보기에 코드 블록은 의미가 없다)
      .replace(/```[\s\S]*?```/g, " ")
      .replace(/~~~[\s\S]*?~~~/g, " ")
      // 이미지는 대체 텍스트만, 링크는 보이는 글자만 남긴다
      .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
      .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
      // 표 구분선(|---|---|)과 수평선(---, ***, ___)
      .replace(/^\s*\|?[\s:|-]*\|[\s:|-]*$/gm, " ")
      .replace(/^\s*(-{3,}|\*{3,}|_{3,})\s*$/gm, " ")
      // 줄머리 기호: 제목(#), 인용(>), 글머리(-,*,+), 번호(1.)
      .replace(/^\s{0,3}#{1,6}\s+/gm, "")
      .replace(/^\s*>\s?/gm, "")
      .replace(/^\s*[-*+]\s+/gm, "")
      .replace(/^\s*\d+[.)]\s+/gm, "")
      // 표의 칸 구분자는 공백으로
      .replace(/\|/g, " ")
      // 강조·코드 표시
      .replace(/(\*\*|__)(.*?)\1/g, "$2")
      .replace(/(\*|_)(.*?)\1/g, "$2")
      .replace(/`([^`]*)`/g, "$1")
      // 백엔드가 이스케이프해 보내는 \[ \] \* 같은 것 되돌리기
      .replace(/\\([\\`*_{}[\]()#+\-.!>])/g, "$1")
      // 줄바꿈·연속 공백을 한 칸으로
      .replace(/\s+/g, " ")
      .trim()
  );
}
